  $("backBtn").addEventListener("click", () => showStep(Math.max(1, currentStep - 1)));

  function drawChart() {
    const canvas = $("bpChart");
    const rect = canvas.getBoundingClientRect();
    const dpr = window.devicePixelRatio || 1;
    canvas.width = Math.max(320, rect.width * dpr);
    canvas.height = 190 * dpr;
    const ctx = canvas.getContext("2d");
    ctx.scale(dpr, dpr);
    const w = canvas.width / dpr, h = 190;
    const pad = {l:34,r:12,t:14,b:28};
    const plotW = w-pad.l-pad.r, plotH = h-pad.t-pad.b;
    ctx.clearRect(0,0,w,h);
    ctx.font = "10px DM Sans, sans-serif";
    ctx.fillStyle = "#8c9aa2";
    [100,120,140,160].forEach(v => {
      const y = pad.t + (160-v)/70*plotH;
      ctx.strokeStyle = "#edf1f2"; ctx.beginPath(); ctx.moveTo(pad.l,y); ctx.lineTo(w-pad.r,y); ctx.stroke();
      ctx.fillText(String(v),4,y+3);
    });
    const day = [126,124,123,125,132,140,145,142,138,134,130,128,126];
    const night = [121,119,116,113,110,108,109,112,116,119,121,123,125];
    function line(data,color) {
      ctx.beginPath();
      data.forEach((v,i) => {
        const x=pad.l+i/12*plotW, y=pad.t+(160-v)/70*plotH;
        if(i===0)ctx.moveTo(x,y);else ctx.lineTo(x,y);
      });
      ctx.strokeStyle=color;ctx.lineWidth=2.5;ctx.lineJoin="round";ctx.stroke();
    }
    line(day,"#37a99e");line(night,"#9485c8");
    ["00","04","08","12","16","20","24"].forEach((v,i)=>ctx.fillText(v,pad.l+i/6*plotW-6,h-8));
  }

  function encodePatient() {
    const classOptions = [...$("drugClass").options].filter(o => o.value);
    const frequencyOptions = [...$("frequency").options];
    const sleepOptions = [...$("sleepTime").options];
    const wakeOptions = [...$("wakeTime").options];
    const patternOptions = [...$("nightPattern").options];
    return [
      Number($("age").value),
      $("sex").value === "Laki-laki" ? 1 : 0,
      Number($("sbp").value),
      Number($("dbp").value),
      Number($("nightSbp").value || 0),
      Math.max(0, classOptions.findIndex(o => o.textContent === $("drugClass").value)),
      Math.max(0, frequencyOptions.findIndex(o => o.value === $("frequency").value)),
      Math.max(0, sleepOptions.findIndex(o => o.value === $("sleepTime").value)),
      Math.max(0, wakeOptions.findIndex(o => o.value === $("wakeTime").value)),
      Math.max(0, patternOptions.findIndex(o => o.value === $("nightPattern").value)),
      $("dizziness").checked ? 1 : 0
    ];
  }

  function explainPrediction(label, nightSbp, sbp, pattern) {
    const patternValue = $("nightPattern").value;
    let detail = `Model Random Forest memetakan kombinasi karakteristik pasien, tekanan darah, terapi obat, dan ritme harian ke kecenderungan waktu pemberian ${label.toLowerCase()}.`;
    if (patternValue === "Tidak menurun saat tidur" || patternValue === "Meningkat saat tidur") {
      detail += " Pola tekanan darah malam yang dimasukkan menunjukkan penurunan yang tidak jelas atau peningkatan saat tidur.";
    } else if (patternValue === "Menurun saat tidur") {
      detail += " Data yang dimasukkan menunjukkan pola penurunan tekanan darah saat tidur.";
    } else if (nightSbp > 0) {
      detail += " Nilai sistolik malam turut dipertimbangkan dalam pemetaan model.";
    } else {
      detail += " Data tekanan darah malam/ABPM belum tersedia, sehingga hasil perlu ditafsirkan dengan kehati-hatian lebih tinggi.";
    }
    return detail;
  }

  function buildResult() {
    const age = Number($("age").value);
    const sbp = Number($("sbp").value);
    const dbp = Number($("dbp").value);
    const nightSbp = Number($("nightSbp").value || 0);
    const drug = $("drugName").value.trim() || $("drugClass").value;
    const dizziness = $("dizziness").checked;
    const features = encodePatient();
    const votes = chronoModel.forest.map(tree => predictTree(tree, features));
    const nightVotes = votes.reduce((sum, value) => sum + value, 0);
    const direction = nightVotes > votes.length / 2 ? "Malam" : "Pagi";
    const winningVotes = direction === "Malam" ? nightVotes : votes.length - nightVotes;
    const reason = explainPrediction(direction, nightSbp, sbp, $("nightPattern").value);
    let caution = "Model ini masih bersifat eksperimental dan belum tervalidasi secara klinis. Hasil tidak boleh digunakan sendiri untuk menentukan atau mengubah waktu maupun dosis terapi.";
    if (dizziness || age >= 65) caution += " Faktor usia atau riwayat pusing/risiko jatuh perlu ditelaah khusus oleh tenaga kesehatan sebelum mempertimbangkan waktu pemberian obat.";
    $("resultDirection").textContent = direction;
    $("resultSummary").textContent = reason;
    $("resultCaution").textContent = caution;
    $("outSbp").textContent = sbp;
    $("outDbp").textContent = dbp;
    $("outDrug").textContent = drug;
    const modelStatus = document.querySelector(".model-status");
    if (modelStatus) modelStatus.textContent = "Belum tervalidasi klinis";
    $("resultCard").hidden = false;
    requestAnimationFrame(drawChart);
    showPage("result");
  }

