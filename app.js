  // Reproducible pseudo-random generator so the same prototype model is rebuilt consistently.
  function makeRandom(seed) {
    let state = seed >>> 0;
    return function () {
      state += 0x6D2B79F5;
      let t = state;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  const random = makeRandom(20261122);
  const randBetween = (min, max) => min + random() * (max - min);
